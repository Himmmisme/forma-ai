  await expect(images).toHaveCount(1);
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: info.outputPath("studio.png") });
  await page.reload();
  await expect(images).toHaveCount(1);
  await images.getByRole("link", { name: "继续修改" }).click();
  await expect(page.getByRole("heading", { name: /当前迭代图片/ })).toBeVisible();
  await page.getByLabel("原始需求").fill("对局部倒角做微调");
