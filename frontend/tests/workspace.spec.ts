  await expect(images).toHaveCount(2);
  await images.first().getByRole("button", { name: "参数" }).click();
  await expect(page.getByRole("dialog", { name: "V002 生成参数" })).toBeVisible();
  await expect(page.getByRole("dialog").getByRole("button", { name: "V001", exact: true })).toBeVisible();
  await page.getByRole("dialog").getByRole("button", { name: "关闭" }).click();
  const download = page.waitForEvent("download");
  await images.first().getByRole("link", { name: "下载" }).click();
  expect((await download).suggestedFilename()).toMatch(/Forma-V002/);
  await images.first().getByRole("link", { name: "对比", exact: true }).click();
  await expect(page.locator(".compare-grid img")).toHaveCount(2);
  await page.goBack();
  await images.first().getByRole("link", { name: "材料分析" }).click();
  await page.getByRole("button", { name: "运行材料分析" }).click();
  await page.getByRole("button", { name: "采用并编辑材料建议" }).click();
  await page.getByRole("button", { name: "保存材料方案" }).click();
  await page.getByRole("button", { name: "按此方案估算" }).click();
  await page.getByLabel("一次性模具费（元）").fill("1000");
  await page.getByRole("button", { name: "计算并保存" }).click();
  await expect(page.getByText("单台制造", { exact: true })).toBeVisible();
  await expect(page.getByText("部分费用待确认", { exact: false })).toBeVisible();
  await page.getByRole("link", { name: "管理后台", exact: true }).click();
  await page.getByRole("button", { name: "API 服务商与模型" }).click();
  await page.getByRole("button", { name: "连接测试", exact: true }).click();
